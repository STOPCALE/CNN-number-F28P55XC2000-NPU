# -*- coding: utf-8 -*-
"""
导出板端 golden 向量: 12 张 MNIST 测试图 (原始 uint8 像素) + PC 参考输出
====================================================================
用法: conda run --no-capture-output -n torch python export_golden.py
产物:
  E:\\desk\\CCS\\cnn_and_number\\golden_mnist.h   (C 头文件, 纯 ASCII)
  runs/cnn32/golden_report.json                  (选样明细存档)

选样规则 (确定性):
  * 0-9 每类选 1 张"PC float 模型预测正确且 logits 边际最大"的测试图
  * 另加 2 张余下边际最大的样本 (共 12 张)
  * 像素 = round(原图*255) 还原为原始 MNIST uint8; 板端输入 = pix/255.0f
  * GOLD_LOGITS = PC float 模型对同一口径输入的参考输出 (板端算 max|d| 用)
"""
import json
import os

import numpy as np
import torch

from config import CFG
from model import build_model

CCS_HEADER = r"E:\desk\CCS\cnn_and_number\golden_mnist.h"
RUN_DIR = CFG.train.out_dir


def main():
    ck = torch.load(os.path.join(RUN_DIR, "best.pt"),
                    map_location="cpu", weights_only=False)
    model = build_model()
    model.load_state_dict(ck["model"])
    model.eval()

    d = np.load(os.path.join(CFG.data.data_dir, "mnist_32.npz"))
    tex, tey = d["test_x"], d["test_y"]          # float [0,1] 32x32 / int
    x = torch.from_numpy(tex).unsqueeze(1)
    with torch.no_grad():
        logits = model(x).numpy()                # (10000,10)
    pred = logits.argmax(1)
    srt = np.sort(logits, axis=1)
    margin = srt[:, -1] - srt[:, -2]

    chosen = []
    for c in range(10):
        idx = np.where((tey == c) & (pred == c))[0]
        chosen.append(int(idx[np.argmax(margin[idx])]))
    rest = np.setdiff1d(np.arange(len(tey)), chosen)
    chosen += [int(i) for i in rest[np.argsort(-margin[rest])[:2]]]

    pix = np.clip(np.round(tex[chosen] * 255.0), 0, 255).astype(np.uint8)

    L = []
    L.append("/* Auto-generated by CNN_TWO/export_golden.py -- DO NOT EDIT.")
    L.append(" * Golden vectors for board-side verification of mnist_cnn (int8, F28P55 NPU).")
    L.append(" * 12 MNIST test samples; pixels are original MNIST uint8 values;")
    L.append(" * board input = pix/255.0f  (same [0,1] convention as PC training).")
    L.append(" * GOLD_EXPECT = PC float-model argmax;  GOLD_LOGITS = PC float output.")
    for k, i in enumerate(chosen):
        L.append(f" *   [{k:02d}] test_idx={i:5d}  true={int(tey[i])} "
                 f"expect={int(pred[i])}  margin={margin[i]:.3f}")
    L.append(" */")
    L.append("#ifndef GOLDEN_MNIST_H")
    L.append("#define GOLDEN_MNIST_H")
    L.append("#include <stdint.h>")
    L.append("")
    L.append("#define GOLD_N_SAMPLES 12")
    L.append("#define GOLD_IMG_W 32")
    L.append("#define GOLD_IMG_H 32")
    L.append("")
    L.append("static const uint8_t GOLD_PIX[GOLD_N_SAMPLES][GOLD_IMG_W*GOLD_IMG_H] = {")
    for k in range(len(chosen)):
        L.append(f"  {{ /* [{k:02d}] */")
        flat = pix[k].reshape(-1)
        for r in range(0, len(flat), 32):
            L.append("    " + ", ".join(f"{int(v):3d}" for v in flat[r:r + 32]) + ",")
        L.append("  },")
    L.append("};")
    L.append("")
    L.append("static const uint8_t GOLD_TRUE[GOLD_N_SAMPLES] = {%s};"
             % ", ".join(str(int(tey[i])) for i in chosen))
    L.append("static const uint8_t GOLD_EXPECT[GOLD_N_SAMPLES] = {%s};"
             % ", ".join(str(int(pred[i])) for i in chosen))
    L.append("")
    L.append("static const float GOLD_LOGITS[GOLD_N_SAMPLES][10] = {")
    for i in chosen:
        L.append("  {%s}," % ", ".join(f"{v:+.4f}f" for v in logits[i]))
    L.append("};")
    L.append("")
    L.append("#endif /* GOLDEN_MNIST_H */")

    os.makedirs(os.path.dirname(CCS_HEADER), exist_ok=True)
    with open(CCS_HEADER, "w", encoding="ascii") as f:
        f.write("\n".join(L) + "\n")

    report = {
        "ccs_header": CCS_HEADER,
        "n_samples": len(chosen),
        "samples": [{"k": k, "test_idx": int(i), "true": int(tey[i]),
                     "expect": int(pred[i]), "margin": float(margin[i])}
                    for k, i in enumerate(chosen)],
    }
    with open(os.path.join(RUN_DIR, "golden_report.json"), "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)

    print(f"[export] {CCS_HEADER}")
    for it in report["samples"]:
        print(f"  [{it['k']:02d}] idx={it['test_idx']:5d} true={it['true']} "
              f"expect={it['expect']} margin={it['margin']:.3f}")


if __name__ == "__main__":
    main()
